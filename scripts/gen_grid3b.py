import io

lines = []

lines.append("  var PGV_FAMILIES = {")
lines.append("    CTB: { name:'CTB · Traitement & conformité', short:'Traitement',  note:'Le parcours SAC et les règles qu’on ne transige pas.' },")
lines.append("    CTC: { name:'CTC · Relation client',         short:'Relation',    note:'Ce que le client vit et comprend : accueil, reformulation, clarté, réclamation, clôture.' },")
lines.append("    NC:  { name:'NC · Savoir être',              short:'Savoir être', note:'La manière de le dire : V.A.T.R.E, professionnalisme, écoute active, empathie, maîtrise de soi.' }")
lines.append("  };")
lines.append("")

lines.append("  var PGV_OBJECTIFS = {")
lines.append("    scoreCible: 85,")
lines.append("    conformiteExigee: true,")
lines.append("    calibragesParMois: 4,")
lines.append("    ecoutesCroiseesParMois: 1,")
lines.append("    progressionCible: 3")
lines.append("  };")
lines.append("")

lines.append("  var PGV_STEPS = {")
lines.append("    0: 'Transverse',")
lines.append("    1: '1 · Réception',")
lines.append("    2: '2 · Identification',")
lines.append("    3: '3 · Qualification',")
lines.append("    4: '4 · Traitement',")
lines.append("    5: '5 · Escalade',")
lines.append("    6: '6 · Clôture'")
lines.append("  };")
lines.append("")

lines.append("  // Calcul du score — formule unique")
lines.append("  // values = ['Oui'|'Non'|'N/A'|'', ...] dans l'ordre de PGV_GRID")
lines.append("  function pgvScore(values) {")
lines.append("    var oui = 0, evalue = 0, repondu = 0;")
lines.append("    var critKO = [];")
lines.append("    var fam = {};")
lines.append("    Object.keys(PGV_FAMILIES).forEach(function (k) { fam[k] = { oui: 0, evalue: 0, pct: null }; });")
lines.append("")
lines.append("    PGV_GRID.forEach(function (g, i) {")
lines.append("      var v = values[i], w = g.weight;")
lines.append("      if (v === 'Oui') {")
lines.append("        oui += w; evalue += w;")
lines.append("        fam[g.cat].oui += w; fam[g.cat].evalue += w;")
lines.append("        repondu++;")
lines.append("      } else if (v === 'Non') {")
lines.append("        evalue += w;")
lines.append("        fam[g.cat].evalue += w;")
lines.append("        repondu++;")
lines.append("        if (g.critical) critKO.push(g.code);")
lines.append("      } else if (v === 'N/A') {")
lines.append("        repondu++;")
lines.append("      }")
lines.append("    });")
lines.append("")
lines.append("    Object.keys(fam).forEach(function (k) {")
lines.append("      var f = fam[k];")
lines.append("      f.pct = f.evalue ? Math.round(f.oui / f.evalue * 100) : null;")
lines.append("    });")
lines.append("")
lines.append("    var pct = evalue ? Math.round(oui / evalue * 100) : 0;")
lines.append("    var complet = repondu === PGV_GRID.length;")
lines.append("")
lines.append("    var niveau;")
lines.append("    if (!complet) niveau = 'incomplet';")
lines.append("    else if (critKO.length > 0) niveau = 'nc';")
lines.append("    else if (pct >= 90) niveau = 'excellent';")
lines.append("    else if (pct >= 85) niveau = 'conforme';")
lines.append("    else if (pct >= 70) niveau = 'consolider';")
lines.append("    else niveau = 'critique';")
lines.append("")
lines.append("    return {")
lines.append("      pct: pct,")
lines.append("      fam: fam,")
lines.append("      complet: complet,")
lines.append("      critKO: critKO,")
lines.append("      nonConforme: critKO.length > 0,")
lines.append("      niveau: niveau,")
lines.append("      totalPoints: evalue,")
lines.append("      obtenuPoints: oui")
lines.append("    };")
lines.append("  }")
lines.append("")

lines.append("  // Expose globally")
lines.append("  window.PGV_GRID = PGV_GRID;")
lines.append("  window.PGV_FAMILIES = PGV_FAMILIES;")
lines.append("  window.PGV_OBJECTIFS = PGV_OBJECTIFS;")
lines.append("  window.PGV_STEPS = PGV_STEPS;")
lines.append("  window.pgvScore = pgvScore;")
lines.append("")
lines.append("  window.pgvElementCountByFamily = function () {")
lines.append("    var c = {};")
lines.append("    Object.keys(PGV_FAMILIES).forEach(function (k) { c[k] = 0; });")
lines.append("    PGV_GRID.forEach(function (g) { c[g.cat]++; });")
lines.append("    return c;")
lines.append("  };")
lines.append("")
lines.append("  window.pgvElementCountByStep = function () {")
lines.append("    var c = {};")
lines.append("    for (var s = 0; s <= 6; s++) c[s] = 0;")
lines.append("    PGV_GRID.forEach(function (g) { c[g.step]++; });")
lines.append("    return c;")
lines.append("  };")
lines.append("")
lines.append("  window.pgvWeightByFamily = function () {")
lines.append("    var w = {};")
lines.append("    Object.keys(PGV_FAMILIES).forEach(function (k) { w[k] = 0; });")
lines.append("    PGV_GRID.forEach(function (g) { w[g.cat] += g.weight; });")
lines.append("    return w;")
lines.append("  };")
lines.append("")
lines.append("  window.pgvWeightByStep = function () {")
lines.append("    var w = {};")
lines.append("    for (var s = 0; s <= 6; s++) w[s] = 0;")
lines.append("    PGV_GRID.forEach(function (g) { w[g.step] += g.weight; });")
lines.append("    return w;")
lines.append("  };")
lines.append("")
lines.append("})();")
lines.append("")

with open("js/pgv-grid.js", "r", encoding="utf-8") as f:
    content = f.read()

content += "\n".join(lines)

with io.open("js/pgv-grid.js", "w", encoding="utf-8") as f:
    f.write(content)
print("Part 3b written: families, objectives, steps, pgvScore, expose")
